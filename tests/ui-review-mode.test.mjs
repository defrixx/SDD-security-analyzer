console.log('PASS: review default, legacy comparison, multiple documents, minimal request, validation and stale-plan source contracts');

const overrides = [{ requirement_id: 'r', predicate_id: 'p', side: 'proposed', value: null, reason: 'Not known', secret: 'omit' }];
const withAnswers = documentReviewRequest(['doc'], ['cat'], {id:'m',revision:1}, {}, false, overrides);
assert.deepEqual(withAnswers.fact_overrides, [{requirement_id:'r',predicate_id:'p',side:'proposed',value:null,reason:'Not known'}]);
assert.notEqual(withAnswers.fact_overrides[0], overrides[0]);
for (const value of [true, false, null]) assert.equal(documentReviewRequest(['doc'],['cat'],{id:'m',revision:1},{},false,[{...overrides[0],value}]).fact_overrides[0].value,value);
assert.ok(runs.includes('report.scope_confirmations?.length'));
assert.ok(runs.includes('Prepare a new review with my answers'));
assert.ok(runs.includes('stepMode.checked, factOverrides'));
console.log('PASS: explicit answers preserved including false/null; no model-derived defaults');

