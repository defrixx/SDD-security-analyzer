const original = ['proposal', 'design', 'proposal'];
const request = documentReviewRequest(original, ['catalog'], {id:'model', revision:3, secret:'not copied'}, {max_requests:10}, false);
assert.deepEqual(request.review_document_ids, ['proposal','design']);
assert.deepEqual(original, ['proposal','design','proposal']);
assert.deepEqual(request.connection, {id:'model',revision:3});
assert.equal(request.mode, 'review_documents');
for (const key of ['delta_document_id','baseline_document_ids','context_document_ids','skill_refs','prompt_refs','pipeline_ref']) assert.ok(!(key in request));
assert.equal(documentReviewRequest([],['catalog'],{id:'m',revision:1},{},false),null);
assert.equal(documentReviewRequest(['doc'],[],{id:'m',revision:1},{},false),null);
assert.equal(documentReviewRequest(['doc'],['catalog'],null,{},false),null);
assert.equal(documentReviewRequest(['doc'],['catalog'],{id:'m',revision:1},{},true).step_mode,true);
const app = await readFile(new URL('../spec_enricher/static/app.js', import.meta.url),'utf8');
assert.ok(app.includes('role.value = "master_spec";'));
