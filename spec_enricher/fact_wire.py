"""Versioned native P3 wire contract; catalogue versions are code-owned metadata."""

from copy import deepcopy
from typing import Literal

from pydantic import Field

from .catalog import digest
from .llm import OutputSchemaError
from .prompts import defaults
from .schema_worker import validate_payload
from .stage_contracts import Citation, Contract, FactsOutput, SourceConflict

WIRE_CONTRACT = "builtin.P3.native.fact-pins.v1"


class WirePredicateFact(Contract):
    requirement_id: str
    predicate_id: str
    side: Literal["baseline", "proposed"]
    evidence: list[Citation] = Field(max_length=12)
    explanation: str = Field(min_length=1, max_length=2000)
    support: Literal["direct", "inferred", "insufficient", "conflicting"]
    question: str | None
    truth: bool | None


class WireFactsOutput(Contract):
    facts: list[WirePredicateFact] = Field(max_length=1000)
    conflicts: list[SourceConflict] = Field(max_length=100)
    questions: list[str] = Field(max_length=100)


def enabled(stage, profile, contract, instruction, *, prompt, schema, skill):
    return (
        stage == "P3"
        and profile.adapter == "lm_studio_native"
        and profile.output_mode == "prompt_json"
        and contract is FactsOutput
        and instruction == defaults()["P3"]
        and prompt is None
        and schema is None
        and skill is None
    )


def pins(records, sides=("baseline", "proposed")):
    """Reject ambiguous pinned inputs instead of choosing a record/version."""
    result = {}
    seen_requirements = set()
    for record in records:
        rid, version = record["id"], record["version"]
        if not isinstance(rid, str) or not isinstance(version, str) or not version:
            raise ValueError("invalid_pinned_fact_metadata")
        if rid in seen_requirements:
            raise ValueError("ambiguous_pinned_fact_metadata")
        seen_requirements.add(rid)
        for predicate in record["applicability"]["predicates"]:
            pid = predicate["id"]
            if not isinstance(pid, str):
                raise ValueError("invalid_pinned_fact_metadata")
            for side in sides:
                key = (rid, pid, side)
                if key in result:
                    raise ValueError("ambiguous_pinned_fact_metadata")
                result[key] = version
    return result


def prepare(bound_canonical_schema, records, sides=("baseline", "proposed")):
    pinned = pins(records, sides)
    # Retain every bound shape/evidence constraint, removing ONLY metadata that
    # is no longer generated by the model. extra=forbid rejects supplied version.
    schema = deepcopy(dict(bound_canonical_schema))
    fact = schema["$defs"]["PredicateFact"]
    del fact["properties"]["version"]
    fact["required"].remove("version")
    schema["title"] = WIRE_CONTRACT
    metadata = {
        "wire_contract": WIRE_CONTRACT,
        "metadata_hydration": "version_from_unique_pinned_requirement_predicate_side",
        "pinned_metadata_sha256": digest(
            [list(key) + [version] for key, version in sorted(pinned.items())]
        ),
    }
    return schema, pinned, metadata


def hydrate(value, schema, pinned):
    # Do not patch a rejected canonical/model result. First validate the explicit
    # wire schema and DTO. The adapter also validates it, but fixtures/callers
    # must not bypass this boundary.
    issues = validate_payload(schema, value)
    if issues:
        raise OutputSchemaError(issues)
    wire = WireFactsOutput.model_validate(value)
    facts, seen = [], set()
    for fact in wire.facts:
        key = (fact.requirement_id, fact.predicate_id, fact.side)
        if key not in pinned or key in seen:
            raise ValueError("unknown_duplicate_or_unpinned_predicate")
        seen.add(key)
        facts.append(fact.model_dump() | {"version": pinned[key]})
    if seen != set(pinned):
        raise ValueError("missing_predicate_coverage")
    return FactsOutput.model_validate(
        {"facts": facts, "conflicts": [x.model_dump() for x in wire.conflicts],
         "questions": wire.questions}
    )
